import { z } from 'zod';
import { writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname } from 'node:path';
import { getActiveSession } from './session.js';

// Converts a live exploratory session into a native Agentforce test spec. By default it writes the Agentforce
// Studio format (AiTestingDefinition, `sf agent test create --test-runner agentforce-studio`); the older
// `sf agent test run-eval` YAML (Beta) is still available with format=run-eval. This turns exploration in
// Claude/Codex into regression tests Salesforce runs in CI.

export const generateTestSpecSchema = z.object({
  sessionId: z
    .string()
    .describe('Session ID of an active or recently-ended exploratory session'),
  agentApiName: z
    .string()
    .describe('Agent API name the test spec should target'),
  suiteName: z
    .string()
    .describe('Name for the generated test suite (kebab-case recommended)'),
  expectedSubagent: z
    .string()
    .optional()
    .describe('Optional: subagent the spec should assert was routed to'),
  expectedActions: z
    .array(z.string())
    .optional()
    .describe('Optional: actions the spec should assert were invoked'),
  outputPath: z
    .string()
    .optional()
    .describe('Where to write the YAML file. Defaults to sfagent-reports/<suiteName>.yaml'),
  format: z
    .enum(['agentforce-studio', 'run-eval'])
    .optional()
    .describe('Spec format. Default agentforce-studio (AiTestingDefinition); run-eval is the older Beta YAML.'),
});

interface TestCase {
  id: string;
  utterance: string;
  conversationHistory?: Array<{ role: 'user' | 'agent'; message: string }>;
  expectedSubagent?: string;
  expectedActions?: string[];
}

function toYaml(spec: {
  suite: string;
  agent: string;
  cases: TestCase[];
}): string {
  const lines: string[] = [];
  lines.push(`# Generated by sfagent-tools from an exploratory session`);
  lines.push(`# Run with: sf agent test run-eval --spec ${spec.suite}.yaml --target-org <alias>`);
  lines.push(`suite: ${spec.suite}`);
  lines.push(`agent:`);
  lines.push(`  apiName: ${spec.agent}`);
  lines.push(`cases:`);
  for (const tc of spec.cases) {
    lines.push(`  - id: ${tc.id}`);
    lines.push(`    utterance: ${JSON.stringify(tc.utterance)}`);
    if (tc.conversationHistory?.length) {
      lines.push(`    conversationHistory:`);
      for (const turn of tc.conversationHistory) {
        lines.push(`      - role: ${turn.role}`);
        lines.push(`        message: ${JSON.stringify(turn.message)}`);
      }
    }
    if (tc.expectedSubagent) {
      lines.push(`    expectedSubagent: ${tc.expectedSubagent}`);
    }
    if (tc.expectedActions?.length) {
      lines.push(`    expectedActions:`);
      for (const action of tc.expectedActions) {
        lines.push(`      - ${action}`);
      }
    }
  }
  return lines.join('\n') + '\n';
}

// Agentforce Studio spec. Agent turns in a conversation history need their subagent, so multi-turn cases are
// only emitted when expectedSubagent is known; otherwise each utterance becomes a single-turn case.
export function toStudioYaml(spec: { name: string; agent: string; cases: TestCase[] }): string {
  const apiName = spec.name.replace(/[^A-Za-z0-9_]/g, '_').replace(/^([^A-Za-z])/, 'T_$1');
  const lines: string[] = [];
  lines.push('# Generated by sfagent-tools from an exploratory session');
  lines.push(`# Create: sf agent test create --spec <this file> --api-name ${apiName} --test-runner agentforce-studio`);
  lines.push(`# Run:    sf agent test run --api-name ${apiName} --wait 20 --json`);
  lines.push(`name: ${apiName}`);
  lines.push(`description: ${JSON.stringify(`Regression cases captured from an exploratory session with ${spec.agent}`)}`);
  lines.push('subjectType: AGENT');
  lines.push(`subjectName: ${spec.agent}`);
  lines.push('testCases:');
  for (const tc of spec.cases) {
    if (tc.conversationHistory?.length && !tc.expectedSubagent) continue;
    lines.push('  - inputs:');
    lines.push(`      - utterance: ${JSON.stringify(tc.utterance)}`);
    if (tc.conversationHistory?.length) {
      lines.push('        conversationHistory:');
      for (const turn of tc.conversationHistory) {
        lines.push(`          - role: ${turn.role}`);
        lines.push(`            message: ${JSON.stringify(turn.message)}`);
        if (turn.role === 'agent') lines.push(`            topic: ${tc.expectedSubagent}`);
      }
    }
    lines.push('    scorers:');
    if (tc.expectedSubagent) {
      lines.push('      - name: topic_sequence_match');
      lines.push(`        expected: ${tc.expectedSubagent}`);
    } else {
      lines.push('      - name: output_latency_milliseconds');
    }
  }
  return lines.join('\n') + '\n';
}

export async function generateTestSpec(args: z.infer<typeof generateTestSpecSchema>) {
  const session = getActiveSession(args.sessionId);
  if (!session) {
    return {
      content: [
        {
          type: 'text' as const,
          text: `Session ${args.sessionId} not found. Run an exploratory session first, then call generate_test_spec before end_session.`,
        },
      ],
    };
  }

  if (!session.messages.length) {
    return {
      content: [
        {
          type: 'text' as const,
          text: `Session ${args.sessionId} has no messages. Send at least one message before generating a spec.`,
        },
      ],
    };
  }

  // Build one test case per user utterance, using the messages that came
  // before it as conversation history. This preserves multi-turn context the
  // way Agentforce DX expects it.
  const cases: TestCase[] = [];
  for (let i = 0; i < session.messages.length; i++) {
    const msg = session.messages[i];
    if (msg.role !== 'user') continue;

    const priorTurns = session.messages.slice(0, i).map((m) => ({
      role: m.role,
      message: m.content,
    }));

    cases.push({
      id: `${args.suiteName}-turn-${cases.length + 1}`,
      utterance: msg.content,
      conversationHistory: priorTurns.length ? priorTurns : undefined,
      expectedSubagent: args.expectedSubagent,
      expectedActions: args.expectedActions,
    });
  }

  const studio = (args.format ?? 'agentforce-studio') === 'agentforce-studio';
  const yaml = studio
    ? toStudioYaml({ name: args.suiteName, agent: args.agentApiName, cases })
    : toYaml({ suite: args.suiteName, agent: args.agentApiName, cases });

  const outputPath = args.outputPath ?? `sfagent-reports/${args.suiteName}.yaml`;
  const dir = dirname(outputPath);
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
  writeFileSync(outputPath, yaml, 'utf-8');

  return {
    content: [
      {
        type: 'text' as const,
        text: JSON.stringify(
          {
            suiteName: args.suiteName,
            cases: cases.length,
            outputPath,
            format: studio ? 'agentforce-studio' : 'run-eval',
            nextStep: studio
              ? `sf agent test create --spec ${outputPath} --api-name <Name> --test-runner agentforce-studio, then sf agent test run --api-name <Name> --wait 20 --json`
              : `sf agent test run-eval --spec ${outputPath} --target-org <alias>`,
            preview: yaml.split('\n').slice(0, 15).join('\n') + '\n...',
          },
          null,
          2
        ),
      },
    ],
  };
}
